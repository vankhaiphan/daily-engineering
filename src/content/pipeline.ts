/**
 * Pure helpers for the content pipeline (candidates, scoring, registry,
 * coverage). Shared by `scripts/content/*` and unit tests; no file I/O here.
 */
import type { CatalogEntry } from "./catalog";
import { normalizeUrl } from "./quality";
import type { Lesson } from "./schema";

export type CandidateStatus = "selected" | "shortlisted" | "rejected" | "published";

export interface CandidateScores {
  /** 1–5 each. */
  technicalRelevance: number;
  educationalDepth: number;
  credibility: number;
  novelty: number;
  careerValue: number;
  /** null when engagement cannot be verified (never estimate it). */
  engagement: number | null;
}

export interface Candidate {
  id: string;
  url: string;
  title: string;
  publisher: string;
  authors: string[];
  publishedOn: string | null;
  discoveredOn: string;
  /** Where it was found (index page URL, search, user request). */
  discoveredVia: string;
  kind: "recent" | "evergreen";
  /** Scheduled track this candidate belongs to (content-pipeline/schedule.json). */
  track?: "morning" | "evening";
  /** Lower-case concepts for duplicate detection against lessons and pending runs. */
  keywords?: string[];
  scores: CandidateScores;
  engagementNote?: string;
  /** Computed by `npm run content:candidates -- --rescore`; do not hand-edit. */
  total: number;
  status: CandidateStatus;
  /** Why it was selected, shortlisted or rejected. */
  decision: string;
  lessonSlug?: string;
}

export interface CandidateFile {
  version: 1;
  candidates: Candidate[];
}

export const SCORE_WEIGHTS = {
  technicalRelevance: 0.25,
  educationalDepth: 0.25,
  credibility: 0.2,
  novelty: 0.15,
  careerValue: 0.15,
} as const;

/** 0–100. Engagement is a ±5 bonus only when it was actually verified. */
export function scoreCandidate(scores: CandidateScores): number {
  const base = (Object.keys(SCORE_WEIGHTS) as (keyof typeof SCORE_WEIGHTS)[]).reduce(
    (sum, key) => sum + ((scores[key] - 1) / 4) * SCORE_WEIGHTS[key],
    0,
  );
  const bonus = scores.engagement === null ? 0 : ((scores.engagement - 3) / 2) * 0.05;
  return Math.round(Math.max(0, Math.min(1, base + bonus)) * 100);
}

export function validateCandidates(file: CandidateFile, lessons: readonly Lesson[]): string[] {
  const errors: string[] = [];
  const ids = new Set<string>();
  const urls = new Map<string, string>();
  const slugs = new Set(lessons.map((l) => l.slug));
  for (const c of file.candidates) {
    const p = `candidate ${c.id}`;
    if (ids.has(c.id)) errors.push(`${p}: duplicate id`);
    ids.add(c.id);
    try {
      if (new URL(c.url).protocol !== "https:") errors.push(`${p}: url must be https`);
    } catch {
      errors.push(`${p}: invalid url`);
    }
    const key = normalizeUrl(c.url);
    if (urls.has(key)) errors.push(`${p}: same article as ${urls.get(key)}`);
    urls.set(key, c.id);
    for (const [k, v] of Object.entries(c.scores)) {
      if (v === null && k === "engagement") continue;
      if (!Number.isInteger(v) || (v as number) < 1 || (v as number) > 5) errors.push(`${p}: score ${k} must be an integer 1–5`);
    }
    if (c.scores.engagement === null && !c.engagementNote) errors.push(`${p}: explain why engagement is not scored`);
    if (c.total !== scoreCandidate(c.scores)) errors.push(`${p}: total ${c.total} ≠ computed ${scoreCandidate(c.scores)} (run --rescore)`);
    if (c.publishedOn !== null && !/^\d{4}-\d{2}-\d{2}$/.test(c.publishedOn)) errors.push(`${p}: publishedOn must be YYYY-MM-DD or null`);
    if (!c.decision.trim()) errors.push(`${p}: decision reason is required`);
    if (c.track !== undefined && c.track !== "morning" && c.track !== "evening") errors.push(`${p}: track must be morning or evening`);
    if ((c.status === "selected" || c.status === "published") && !c.lessonSlug) errors.push(`${p}: ${c.status} candidates need a lessonSlug`);
    if (c.status === "published" && c.lessonSlug && !slugs.has(c.lessonSlug)) errors.push(`${p}: lesson ${c.lessonSlug} not found`);
  }
  return errors;
}

/** Source of `src/content/lessons/registry.ts`, generated from the catalog. */
export function renderRegistry(catalog: readonly CatalogEntry[]): string {
  const imports = catalog.map((e, i) => `import lesson${i} from "./${e.slug}";`).join("\n");
  const list = catalog.map((_, i) => `lesson${i}`).join(", ");
  return `// GENERATED by \`npm run content:registry\` from src/content/catalog.json — do not edit by hand.
import type { Lesson } from "../schema";
${imports}

export const REGISTERED_LESSONS: readonly Lesson[] = [${list}];
`;
}

export interface CoverageEntry {
  slug: string;
  status: Lesson["status"];
  createdOn: string;
  title: string;
  topics: string[];
  keywords: string[];
  sources: string[];
}

/** What has been covered: used to reject duplicate topics during discovery. */
export function buildCoverage(lessons: readonly Lesson[]): { version: 1; lessons: CoverageEntry[] } {
  return {
    version: 1,
    lessons: lessons
      .map((l) => ({
        slug: l.slug,
        status: l.status,
        createdOn: l.createdOn,
        title: l.content.en.title,
        topics: [...l.topics],
        keywords: [...l.keywords],
        sources: l.sources.map((s) => normalizeUrl(s.url)),
      }))
      .sort((a, b) => a.slug.localeCompare(b.slug)),
  };
}
